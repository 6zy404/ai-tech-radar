import { afterEach, describe, expect, it, vi } from "vitest";

import type {
  AiGenerationCallHooks,
  AiGenerationMetadata
} from "@/lib/ai-generation-record";
import { generateOrGetTechnologyComparison } from "@/lib/technology-comparison";
import { generateOrGetTechnologyExplanation } from "@/lib/technology-explanation";
import { generateOrGetTechnologyLearningPath } from "@/lib/technology-learning-path";
import type {
  TechnologyComparisonRecord,
  TechnologyExplanationRecord,
  TechnologyLearningPathRecord
} from "@/types/content";

// The three public AI caches share one rule (isReusableCachedAiRecord); this
// file checks each generator actually applies it: a mock answer cached before
// a key was configured is regenerated by the real model, and nothing else is.
// It also pins where the site-wide daily cap is counted: `onProviderCall`
// fires exactly when the model is called, so a cache hit never counts.

const { stores, generateMock } = vi.hoisted(() => ({
  stores: {
    explanations: new Map<string, TechnologyExplanationRecord>(),
    comparisons: new Map<string, TechnologyComparisonRecord>(),
    learningPaths: new Map<string, TechnologyLearningPathRecord>()
  },
  generateMock: vi.fn()
}));

vi.mock("@/lib/content", () => {
  const technologies = ["tech-a", "tech-b"].map((id) => ({
    id,
    relatedKnowledgeIds: [],
    relatedSkillIds: []
  }));

  return {
    getAllTechnologies: () => technologies,
    getAllKnowledge: () => [],
    getAllSkills: () => [],
    findRelationBetween: () => undefined
  };
});

vi.mock("@/lib/llm/providers", () => ({
  createConfiguredLlmProvider: () => ({ generate: generateMock })
}));

vi.mock("@/lib/prompt-versions", () => ({
  ensureDefaultPromptVersion: () => undefined
}));

vi.mock("@/lib/workflow-events", () => ({
  tryRecordWorkflowEvent: () => undefined
}));

vi.mock("@/lib/llm/prompts/technology-explanation", () => ({
  buildTechnologyExplanationPrompt: () => ({
    systemPrompt: "explanation",
    userPrompt: "",
    promptVersion: "v1",
    promptVersionId: "p1"
  })
}));

vi.mock("@/lib/llm/prompts/technology-comparison", () => ({
  buildTechnologyComparisonPrompt: () => ({
    systemPrompt: "comparison",
    userPrompt: "",
    promptVersion: "v1",
    promptVersionId: "p1"
  })
}));

vi.mock("@/lib/llm/prompts/technology-learning-path", () => ({
  buildTechnologyLearningPathPrompt: () => ({
    systemPrompt: "learning-path",
    userPrompt: "",
    promptVersion: "v1",
    promptVersionId: "p1"
  })
}));

vi.mock("@/lib/technology-explanation-store", () => ({
  getExplanationCacheKey: (id: string, level: string) => `${id}::${level}`,
  getTechnologyExplanationByCacheKey: (key: string) =>
    stores.explanations.get(key),
  saveTechnologyExplanationRecord: (record: TechnologyExplanationRecord) => {
    stores.explanations.set(record.cacheKey, record);
    return record;
  }
}));

vi.mock("@/lib/technology-comparison-store", () => ({
  getComparisonPairKey: (a: string, b: string) => [a, b].sort().join("::"),
  getTechnologyComparisonByPairKey: (key: string) =>
    stores.comparisons.get(key),
  saveTechnologyComparisonRecord: (record: TechnologyComparisonRecord) => {
    stores.comparisons.set(record.pairKey, record);
    return record;
  }
}));

vi.mock("@/lib/technology-learning-path-store", () => ({
  getTechnologyLearningPathByTechnologyId: (id: string) =>
    stores.learningPaths.get(id),
  saveTechnologyLearningPathRecord: (record: TechnologyLearningPathRecord) => {
    stores.learningPaths.set(record.technologyId, record);
    return record;
  }
}));

const modelOutput: Record<string, string> = {
  explanation: JSON.stringify({
    explanation: "模型写的解读。",
    keyPoints: ["要点"]
  }),
  comparison: JSON.stringify({
    similarities: ["相同点"],
    differences: ["不同点"],
    whenToPreferA: "模型写的对比。",
    whenToPreferB: "选 B 的场合。"
  }),
  "learning-path": JSON.stringify({
    overview: "模型写的学习路径。",
    steps: ["第一步"]
  })
};

function cachedMetadata(
  generationMode: AiGenerationMetadata["generationMode"]
): AiGenerationMetadata {
  return {
    generationMode,
    outputValidationStatus: "valid",
    outputValidationWarnings: [],
    createdAt: "2026-07-29T00:00:00.000Z",
    updatedAt: "2026-07-29T00:00:00.000Z"
  };
}

type CacheCase = {
  name: string;
  seed: (mode: AiGenerationMetadata["generationMode"]) => void;
  run: (hooks?: AiGenerationCallHooks) => Promise<string | undefined>;
  stored: () => AiGenerationMetadata & { id: string };
};

const cases: CacheCase[] = [
  {
    name: "explanation",
    seed: (mode) =>
      stores.explanations.set("tech-a::intermediate", {
        id: "cached-record",
        cacheKey: "tech-a::intermediate",
        technologyId: "tech-a",
        audienceLevel: "intermediate",
        fields: { explanation: "缓存里的解读。", keyPoints: [] },
        ...cachedMetadata(mode)
      }),
    run: async (hooks) => {
      const outcome = await generateOrGetTechnologyExplanation(
        "tech-a",
        "intermediate",
        hooks
      );
      return "result" in outcome
        ? outcome.result.fields.explanation
        : undefined;
    },
    stored: () => stores.explanations.get("tech-a::intermediate")!
  },
  {
    name: "comparison",
    seed: (mode) =>
      stores.comparisons.set("tech-a::tech-b", {
        id: "cached-record",
        pairKey: "tech-a::tech-b",
        technologyIdA: "tech-a",
        technologyIdB: "tech-b",
        fields: {
          similarities: [],
          differences: [],
          whenToPreferA: "缓存里的对比。",
          whenToPreferB: ""
        },
        ...cachedMetadata(mode)
      }),
    run: async (hooks) => {
      const outcome = await generateOrGetTechnologyComparison(
        "tech-b",
        "tech-a",
        hooks
      );
      return "result" in outcome
        ? outcome.result.fields.whenToPreferA
        : undefined;
    },
    stored: () => stores.comparisons.get("tech-a::tech-b")!
  },
  {
    name: "learning path",
    seed: (mode) =>
      stores.learningPaths.set("tech-a", {
        id: "cached-record",
        technologyId: "tech-a",
        fields: { overview: "缓存里的学习路径。", steps: [] },
        ...cachedMetadata(mode)
      }),
    run: async (hooks) => {
      const outcome = await generateOrGetTechnologyLearningPath(
        "tech-a",
        hooks
      );
      return "result" in outcome ? outcome.result.fields.overview : undefined;
    },
    stored: () => stores.learningPaths.get("tech-a")!
  }
];

function useRealModel() {
  vi.stubEnv("LLM_PROVIDER", "openai_compatible");
  vi.stubEnv("LLM_API_KEY", "test-key");
}

function useMockModel() {
  vi.stubEnv("LLM_PROVIDER", "mock");
  vi.stubEnv("LLM_API_KEY", "");
}

afterEach(() => {
  vi.unstubAllEnvs();
  generateMock.mockReset();
  stores.explanations.clear();
  stores.comparisons.clear();
  stores.learningPaths.clear();
});

describe.each(cases)("the $name cache", ({ seed, run, stored }) => {
  it("regenerates a mock record once a real model is configured", async () => {
    useRealModel();
    seed("mock_llm");
    generateMock.mockImplementation(
      async ({ systemPrompt }: { systemPrompt: string }) => ({
        text: modelOutput[systemPrompt],
        providerName: "openai-compatible",
        modelName: "test-model"
      })
    );

    const text = await run();

    expect(generateMock).toHaveBeenCalledTimes(1);
    expect(text).toMatch(/^模型写的/);
    expect(stored()).toMatchObject({
      id: "cached-record",
      generationMode: "llm_assisted",
      createdAt: "2026-07-29T00:00:00.000Z"
    });
  });

  it("serves a real model's record from the cache", async () => {
    useRealModel();
    seed("llm_assisted");

    const text = await run();

    expect(generateMock).not.toHaveBeenCalled();
    expect(text).toMatch(/^缓存里的/);
  });

  it("serves a mock record while the provider is still the mock", async () => {
    useMockModel();
    seed("mock_llm");

    const text = await run();

    expect(generateMock).not.toHaveBeenCalled();
    expect(text).toMatch(/^缓存里的/);
  });

  it("reports the model call through onProviderCall on a cache miss", async () => {
    useRealModel();
    generateMock.mockImplementation(
      async ({ systemPrompt }: { systemPrompt: string }) => ({
        text: modelOutput[systemPrompt],
        providerName: "openai-compatible",
        modelName: "test-model"
      })
    );
    const onProviderCall = vi.fn();

    await run({ onProviderCall });

    expect(generateMock).toHaveBeenCalledTimes(1);
    expect(onProviderCall).toHaveBeenCalledTimes(1);
    // Counted before the provider answered, not after.
    expect(onProviderCall.mock.invocationCallOrder[0]).toBeLessThan(
      generateMock.mock.invocationCallOrder[0]
    );
  });

  it("does not call onProviderCall on a cache hit", async () => {
    useRealModel();
    seed("llm_assisted");
    const onProviderCall = vi.fn();

    await run({ onProviderCall });

    expect(generateMock).not.toHaveBeenCalled();
    expect(onProviderCall).not.toHaveBeenCalled();
  });
});
