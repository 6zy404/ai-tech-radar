// The service worker served at /sw.js (src/app/sw.js/route.ts), built as a
// string so it can carry the build id as its cache version: every deploy
// changes the script's bytes, the browser installs the new worker, and its
// activate step deletes every cache the previous build left.
//
// What it caches, and nothing else:
//   - the shell: /offline, the manifest and the icons, plus the /_next/static
//     files the offline page uses (precached on install);
//   - /_next/static files as pages load them (hashed names, cache-first;
//     not in `next dev`, where those names do not change with the content);
//   - the signal pages the reader saved for 稍后读. The page posts the saved
//     signals as short hashed keys; the worker maps them to paths with
//     /pwa/signal-paths.json (the same file for everyone, so the server never
//     learns which were saved) and keeps exactly those pages.
// Pages are network-first: online, the reader always gets the live page.
// Offline, a saved page comes from the cache and anything else gets /offline.
//
// It never touches the workspace or any API: `pwaRequestKind` returns
// "bypass" for /workspace, /api (all of it, /api/workspace included),
// /candidates and /technologies/drafts, so those requests go straight to the
// network as if there were no worker. That rule is a pure function so the
// tests can pin it; it is copied into the script with `toString()`, so it must
// not reference anything outside its own body.

export type PwaRequestKind = "bypass" | "static" | "asset" | "page";

export function pwaRequestKind(
  pathname: string,
  search: string,
  isNavigation: boolean,
  isRscRequest: boolean,
  isDev: boolean
): PwaRequestKind {
  const neverTouched = [
    "/api",
    "/workspace",
    "/candidates",
    "/technologies/drafts",
    "/sw.js",
    "/_next/webpack-hmr"
  ];

  for (const prefix of neverTouched) {
    if (pathname === prefix || pathname.indexOf(prefix + "/") === 0) {
      return "bypass";
    }
  }

  if (isRscRequest || search.indexOf("_rsc=") !== -1) {
    return "bypass";
  }

  if (pathname.indexOf("/_next/static/") === 0) {
    return isDev ? "bypass" : "static";
  }

  if (
    pathname === "/manifest.webmanifest" ||
    pathname === "/icon.svg" ||
    pathname === "/favicon.ico" ||
    pathname === "/apple-touch-icon.png" ||
    pathname.indexOf("/icons/") === 0
  ) {
    return "asset";
  }

  return isNavigation ? "page" : "bypass";
}

export const pwaOfflinePath = "/offline";
export const pwaSignalPathsPath = "/pwa/signal-paths.json";
/** Cache key of the saved-pages index ({ keys, pages: [{ url, title }] }). */
export const pwaSavedIndexKey = "/__pwa/saved-index";
export const pwaSavedCachePrefix = "radar-saved-";
export const pwaSavedKeysMessageType = "radar:saved-keys";

export function buildServiceWorkerScript(
  version: string,
  isDev: boolean
): string {
  const constants = {
    VERSION: version,
    IS_DEV: isDev,
    OFFLINE_URL: pwaOfflinePath,
    SIGNAL_PATHS_URL: pwaSignalPathsPath,
    SAVED_INDEX_KEY: pwaSavedIndexKey,
    STATIC_CACHE: `radar-static-${version}`,
    SHELL_CACHE: `radar-shell-${version}`,
    SAVED_CACHE: `${pwaSavedCachePrefix}${version}`,
    SAVED_KEYS_MESSAGE: pwaSavedKeysMessageType
  };

  return `/* AI Tech Radar service worker — generated by src/lib/pwa-service-worker.ts */
"use strict";
${Object.entries(constants)
  .map(([name, value]) => `const ${name} = ${JSON.stringify(value)};`)
  .join("\n")}
const CURRENT_CACHES = [STATIC_CACHE, SHELL_CACHE, SAVED_CACHE];
const SHELL_URLS = [OFFLINE_URL, "/manifest.webmanifest", "/icons/icon-192.png", "/icons/badge-96.png"];
const pwaRequestKind = (${pwaRequestKind.toString()});

function staticUrlsIn(html) {
  if (IS_DEV) return [];
  const found = new Set();
  const pattern = /\\/_next\\/static\\/[^"'\\s)<>]+/g;
  let match;
  while ((match = pattern.exec(html))) found.add(match[0].replace(/&amp;/g, "&"));
  return [...found];
}

async function cacheStaticUrls(urls) {
  if (urls.length === 0) return;
  const cache = await caches.open(STATIC_CACHE);
  await Promise.all(urls.map(async (url) => {
    if (await cache.match(url)) return;
    try {
      const response = await fetch(url);
      if (response.ok) await cache.put(url, response);
    } catch (error) {}
  }));
}

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const shell = await caches.open(SHELL_CACHE);
    await shell.addAll(SHELL_URLS);
    const offline = await shell.match(OFFLINE_URL);
    if (offline) await cacheStaticUrls(staticUrlsIn(await offline.text()));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names
      .filter((name) => name.indexOf("radar-") === 0 && CURRENT_CACHES.indexOf(name) === -1)
      .map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

async function cacheFirst(request) {
  const cache = await caches.open(STATIC_CACHE);
  const cached = await cache.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok) cache.put(request, response.clone());
  return response;
}

async function staleWhileRevalidate(request) {
  const cache = await caches.open(SHELL_CACHE);
  const cached = await cache.match(request, { ignoreSearch: true });
  const network = fetch(request).then((response) => {
    if (response.ok) cache.put(request, response.clone());
    return response;
  }).catch(() => cached);
  return cached || network;
}

async function networkFirstPage(request, url) {
  const saved = await caches.open(SAVED_CACHE);
  try {
    const response = await fetch(request);
    if (response.ok && (await saved.match(url.pathname))) {
      saved.put(url.pathname, response.clone());
    }
    return response;
  } catch (error) {
    const cached = await saved.match(url.pathname);
    if (cached) return cached;
    const shell = await caches.open(SHELL_CACHE);
    return (await shell.match(OFFLINE_URL)) ||
      new Response("现在离线。", { status: 503, headers: { "Content-Type": "text/plain; charset=utf-8" } });
  }
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  const kind = pwaRequestKind(url.pathname, url.search, request.mode === "navigate", request.headers.get("RSC") === "1", IS_DEV);
  if (kind === "static") event.respondWith(cacheFirst(request));
  else if (kind === "asset") event.respondWith(staleWhileRevalidate(request));
  else if (kind === "page") event.respondWith(networkFirstPage(request, url));
});

function decodeTitle(raw) {
  return raw.replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"').replace(/&#x27;|&#39;/g, "'").trim();
}

async function syncSavedPages(savedKeys) {
  const cache = await caches.open(SAVED_CACHE);
  const indexResponse = await cache.match(SAVED_INDEX_KEY);
  const index = indexResponse ? await indexResponse.json() : { keys: [], pages: [] };
  const wantedKeys = [...new Set(savedKeys)].sort();
  if (wantedKeys.join(",") === (index.keys || []).join(",")) return;

  let wantedPaths = [];
  if (wantedKeys.length > 0) {
    const response = await fetch(SIGNAL_PATHS_URL, { cache: "no-store" });
    if (!response.ok) return;
    const paths = (await response.json()).paths || {};
    wantedPaths = wantedKeys.map((key) => paths[key]).filter((path) => typeof path === "string");
  }

  const keys = await cache.keys();
  await Promise.all(keys.map((key) => {
    const path = new URL(key.url).pathname;
    return path === SAVED_INDEX_KEY || wantedPaths.indexOf(path) !== -1 ? null : cache.delete(key);
  }));

  const known = new Map((index.pages || []).map((page) => [page.url, page.title]));
  const pages = [];
  for (const path of wantedPaths) {
    let title = known.get(path);
    if (!title || !(await cache.match(path))) {
      try {
        const response = await fetch(path, { credentials: "same-origin" });
        if (!response.ok) continue;
        const html = await response.clone().text();
        const match = /<title>([^<]*)<\\/title>/i.exec(html);
        title = match ? decodeTitle(match[1]) : path;
        await cache.put(path, response);
        await cacheStaticUrls(staticUrlsIn(html));
      } catch (error) {
        continue;
      }
    }
    pages.push({ url: path, title: title });
  }

  // Only a complete sync records the keys, so a failed fetch is retried on the
  // next page load instead of being remembered as done.
  const complete = pages.length === wantedPaths.length;
  await cache.put(SAVED_INDEX_KEY, new Response(JSON.stringify({
    keys: complete ? wantedKeys : [],
    pages: pages
  }), { headers: { "Content-Type": "application/json" } }));
}

self.addEventListener("message", (event) => {
  const data = event.data;
  if (!data || data.type !== SAVED_KEYS_MESSAGE || !Array.isArray(data.keys)) return;
  const savedKeys = data.keys.filter((key) => typeof key === "string").slice(0, 500);
  event.waitUntil(syncSavedPages(savedKeys).catch(() => undefined));
});

self.addEventListener("push", (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch (error) {
    data = { body: event.data ? event.data.text() : "" };
  }
  const title = typeof data.title === "string" && data.title ? data.title : "AI Tech Radar";
  event.waitUntil(self.registration.showNotification(title, {
    body: typeof data.body === "string" ? data.body : "",
    icon: "/icons/icon-192.png",
    badge: "/icons/badge-96.png",
    tag: typeof data.tag === "string" ? data.tag : undefined,
    lang: "zh-CN",
    data: { url: typeof data.url === "string" ? data.url : "/" }
  }));
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  let target;
  try {
    target = new URL((event.notification.data && event.notification.data.url) || "/", self.location.origin);
  } catch (error) {
    target = new URL("/", self.location.origin);
  }
  // Only ever open this site.
  if (target.origin !== self.location.origin) target = new URL("/", self.location.origin);
  event.waitUntil((async () => {
    const windows = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
    for (const client of windows) {
      if (client.url === target.href && "focus" in client) return client.focus();
    }
    return self.clients.openWindow(target.href);
  })());
});
`;
}
